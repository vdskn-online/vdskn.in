// DISPLAY SERVICES

function displayServices(list) {

    const container =
        document.getElementById("serviceList");

    container.innerHTML = "";


    if (list.length === 0) {

        container.innerHTML =
            "<p style='text-align:center;grid-column:1/-1;'>ಸೇವೆ ಸಿಗಲಿಲ್ಲ ❌</p>";

        return;
    }


    list.forEach(service => {

        const card = document.createElement("div");

        card.className = "service-card";

        card.innerHTML = `

            <h3>${service.name}</h3>

            <p class="department-name">
                📂 ${service.departmentName}
            </p>

            <button
                class="view-btn"
                onclick="showDetails(${service.id})">

                📋 ದಾಖಲೆಗಳು ನೋಡಿ

            </button>

        `;

        container.appendChild(card);

    });

}


// SHOW DETAILS

function showDetails(id) {

    const service =
        services.find(s => s.id === id);

    document.getElementById("modalTitle")
        .textContent = service.name;


    const documents =
        document.getElementById("modalDocuments");

    documents.innerHTML = "";


    service.documents.forEach(doc => {

        const li = document.createElement("li");

        li.textContent = "✓ " + doc;

        documents.appendChild(li);

    });


    document.getElementById("applyButton")
        .onclick = function() {

            applyService(service.name);

        };


    document.getElementById("serviceModal")
        .style.display = "block";
}


// CLOSE

function closeModal() {

    document.getElementById("serviceModal")
        .style.display = "none";
}


// SEARCH

function searchServices() {

    const search =
        document.getElementById("searchInput")
        .value
        .toLowerCase();


    const result =
        services.filter(service =>
            service.name.toLowerCase()
            .includes(search)
        );


    displayServices(result);
}


// FILTER

function filterServices(department) {

    if (department === "all") {

        displayServices(services);

        return;
    }


    const result =
        services.filter(service =>
            service.department === department
        );


    displayServices(result);
}


